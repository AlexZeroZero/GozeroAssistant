"""Generate exact consensus constants and fixtures; no network or mining."""
import hashlib
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
REFERENCE = ROOT.parent / 'noid'
sys.path.insert(0, str(REFERENCE))
from reference import TABLES, multiply, convert


def word(value):
    value = int(value, 16) if isinstance(value, str) else value
    return '{' + ','.join('0x%08xu' % ((value >> (32 * i)) & 0xffffffff) for i in range(4)) + '}'


def array(value):
    return '{' + ','.join(array(x) if isinstance(x, list) else word(x) for x in value) + '}'


def tower_header(diagonal):
    """Derive sparse tower maps from the pinned, independent flat reference.

    Upstream noid_core/src/tower uses AES GF(256) and quadratic extensions.
    Partial MDS coefficients lie in GF(65536), so they act independently on
    each 16-bit coordinate of a tower element. Verify that fact, don't assume it.
    """
    text = '// Generated by generate.py. Apache-2.0; see NOTICE.\n'
    for name, table in [('HT2F', 'TOWER_TO_FLAT'), ('HF2T', 'FLAT_TO_TOWER')]:
        values = [[convert(n << (4 * pos), table) for n in range(16)] for pos in range(32)]
        text += 'GZ_CONSTANT U ' + name + '[32][16] = ' + array(values) + ';\n'
    text += '''static inline U towerBasis(U a, GZ_TABLE U table[32][16]) {
    U r={0,0,0,0}; W words[4]={a.x,a.y,a.z,a.w};
    for(W j=0;j<4;++j) for(W i=0;i<8;++i)
        r=gx(r,table[j*8+i][(words[j]>>(4*i))&15u]);
    return r;
}
'''
    for k, coefficient in enumerate(diagonal):
        images = [convert(multiply(convert(1 << i, 'TOWER_TO_FLAT'), coefficient), 'FLAT_TO_TOWER') for i in range(128)]
        assert all(images[i] < 65536 for i in range(16))
        assert all(images[i] == images[i % 16] << (16 * (i // 16)) for i in range(128))
        masks = {}
        for i in range(16):
            for j in range(16):
                if (images[i] >> j) & 1:
                    masks[j-i] = masks.get(j-i, 0) | (1 << i) | (1 << (i+16))
        terms = []
        for shift, mask in sorted(masks.items()):
            term = '(a&0x%08xu)' % mask
            if shift:
                term = '(' + term + ('<<' if shift > 0 else '>>') + str(abs(shift)) + ')'
            terms.append(term)
        text += 'static inline W towerWord%d(W a){return %s;}\n' % (k, '^'.join(terms))
        text += 'static inline U towerDiagonal%d(U a){return {%s};}\n' % (k, ','.join('towerWord%d(a.%s)' % (k, w) for w in 'xyzw'))
    return text


def generate(check=False):
    source = (REFERENCE / 'pool-vectors.json').read_bytes()
    provenance = json.loads((ROOT / 'provenance.json').read_text())
    if hashlib.sha256(source).hexdigest() != provenance['vectorsSha256']:
        raise ValueError('Pinned vector SHA256 mismatch')
    if hashlib.sha256((REFERENCE / 'constants.json').read_bytes()).hexdigest() != provenance['constantsSha256']:
        raise ValueError('Pinned consensus constants SHA256 mismatch')
    two, four = convert(2, 'TOWER_TO_FLAT'), convert(4, 'TOWER_TO_FLAT')
    diagonal = [int(TABLES['mds_partial_flat'][i][i], 16) ^ 1 for i in range(4)]
    linear = [[[multiply(n << (4 * pos), coefficient) for n in range(16)]
               for pos in range(32)] for coefficient in [two, four] + diagonal]
    entries = [('RC[4][66]', TABLES['round_constants_flat']),
               ('IV[2]', TABLES['powhdr_iv_flat']),
               ('T2F[128]', TABLES['TOWER_TO_FLAT']),
               ('F2T[128]', TABLES['FLAT_TO_TOWER']),
               ('MDS_COEFFICIENTS[6]', [two, four] + diagonal),
               ('LINEAR[6][32][16]', linear)]
    text = '// Generated by generate.py. Apache-2.0 consensus parameters; see NOTICE.\n'
    text += '\n'.join('GZ_CONSTANT U ' + name + ' = ' + array(data) + ';' for name, data in entries)
    vectors = json.loads(source)
    fixtures = []
    for v in vectors['pow_vectors']:
        header = bytearray.fromhex(v['fields_hex'])
        header[160:176] = bytes.fromhex(v['nonce_field10_le_hex'])
        fixtures.append({'name': v['name'], 'header': header.hex(), 'digest': v['digest_hex_le']})
    for v in vectors['mainnet_header_vectors']:
        header = bytearray.fromhex(v['pow_fields_hex_nonce_zeroed'])
        header[160:176] = bytes.fromhex(v['nonce_le_hex'])
        fixtures.append({'name': 'mainnet-' + str(v['height']), 'header': header.hex(), 'digest': v['digest_hex_le']})
    fixture_header = '// Generated by generate.py; see NOTICE.\n'
    fixture_header += 'struct Fixture { const char* name; const char* header; const char* digest; };\n'
    fixture_header += 'static const Fixture FIXTURES[] = {\n'
    fixture_header += ',\n'.join('{' + ','.join(json.dumps(v[k]) for k in ('name', 'header', 'digest')) + '}' for v in fixtures)
    fixture_header += '\n};\n'
    outputs = {'constants.h': text + '\n', 'fixtures.json': json.dumps(fixtures, indent=2) + '\n', 'fixtures.h': fixture_header,
               'tower_linear.h': tower_header(diagonal)}
    for name, content in outputs.items():
        path = ROOT / name
        if check:
            if not path.exists() or path.read_bytes() != content.encode('utf-8'):
                raise ValueError('Generated file differs: ' + name)
        else:
            path.write_bytes(content.encode('utf-8'))
    print(('Verified' if check else 'Generated') + ' constants and %d pool fixtures' % len(fixtures))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
