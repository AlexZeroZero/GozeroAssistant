"""Generate exact consensus constants and fixtures; no network or mining."""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
REFERENCE = ROOT.parent / 'noid'
sys.path.insert(0, str(REFERENCE))
from reference import TABLES, multiply, convert


def word(value):
    value = int(value, 16) if isinstance(value, str) else value
    return '{' + ','.join('0x%08xu' % ((value >> (32 * i)) & 0xffffffff) for i in range(4)) + '}'


def array(value):
    return '{' + ','.join(array(x) if isinstance(x, list) else word(x) for x in value) + '}'


def generate():
    source = (REFERENCE / 'pool-vectors.json').read_bytes()
    provenance = json.loads((REFERENCE / 'provenance.json').read_text())
    if hashlib.sha256(source).hexdigest() != provenance['vectorsSha256']:
        raise ValueError('Pinned vector SHA256 mismatch')
    two, four = convert(2, 'TOWER_TO_FLAT'), convert(4, 'TOWER_TO_FLAT')
    diagonal = [int(TABLES['mds_partial_flat'][i][i], 16) ^ 1 for i in range(4)]
    linear = [[[multiply(n << (4 * pos), coefficient) for n in range(16)]
               for pos in range(32)] for coefficient in [two, four] + diagonal]
    entries = [('RC[4][66]', TABLES['round_constants_flat']),
               ('IV[2]', TABLES['powhdr_iv_flat']),
               ('T2F[128]', TABLES['TOWER_TO_FLAT']),
               ('F2T[128]', TABLES['FLAT_TO_TOWER']),
               ('MDS_COEFFICIENTS[6]', [two, four] + diagonal),
               ('LINEAR[6][32][16]', linear)]
    text = '// Generated by generate.py. Apache-2.0 consensus parameters; see NOTICE.\n'
    text += '\n'.join('GZ_CONSTANT U ' + name + ' = ' + array(data) + ';' for name, data in entries)
    (ROOT / 'constants.h').write_text(text + '\n', encoding='utf-8')
    vectors = json.loads(source)
    fixtures = []
    for v in vectors['pow_vectors']:
        header = bytearray.fromhex(v['fields_hex'])
        header[160:176] = bytes.fromhex(v['nonce_field10_le_hex'])
        fixtures.append({'name': v['name'], 'header': header.hex(), 'digest': v['digest_hex_le']})
    for v in vectors['mainnet_header_vectors']:
        header = bytearray.fromhex(v['pow_fields_hex_nonce_zeroed'])
        header[160:176] = bytes.fromhex(v['nonce_le_hex'])
        fixtures.append({'name': 'mainnet-' + str(v['height']), 'header': header.hex(), 'digest': v['digest_hex_le']})
    (ROOT / 'fixtures.json').write_text(json.dumps(fixtures, indent=2) + '\n', encoding='utf-8')
    print('Generated constants and %d pool fixtures' % len(fixtures))


if __name__ == '__main__':
    generate()
