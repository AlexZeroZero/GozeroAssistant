"""Generate an auditable SHA-256 compression with a 16-word rolling schedule.
The consensus SHA-256d/nonce serialization is unchanged. MIT derivative of the
pinned YSKAR SHA functions; generated output retains provenance comments.
"""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parent
def generate():
 source=(ROOT/'upstream/node-core/gpu/yskar_sha256.h').read_text(encoding='utf-8')
 constants=re.findall(r'0x[0-9a-f]+u',source.split('YSKAR_K[64] = {',1)[1].split('};',1)[0])
 assert len(constants)==64
 lines=['// Generated by generate_fast_sha.py; do not hand-edit.',
 '// MIT derivative: Copyright (c) 2026 The YSKAR developers.',
 '// Gozero: rolling 16-word message schedule, explicitly unrolled 64 rounds.',
 '__device__ __forceinline__ void gz_sha_block(uint32_t s[8],const uint32_t in[16]) {']
 lines += [' uint32_t '+','.join(f'w{i}=in[{i}]' for i in range(16))+';']
 lines += [' uint32_t '+','.join(f'{name}=s[{i}]' for i,name in enumerate('abcdefgh'))+';']
 for i in range(64):
  if i>=16:
   p,q,r,t=[f'w{j%16}' for j in [i,i-15,i-2,i-7]]
   lines += [f' {p}+= (YSKAR_ROTR({q},7)^YSKAR_ROTR({q},18)^({q}>>3)) + {t} + (YSKAR_ROTR({r},17)^YSKAR_ROTR({r},19)^({r}>>10));']
  a,b,c,d,e,f,g,h=['abcdefgh'[(j-i)%8] for j in range(8)]
  lines += [f' {{ uint32_t t1={h}+(YSKAR_ROTR({e},6)^YSKAR_ROTR({e},11)^YSKAR_ROTR({e},25))+(({e}&{f})^(~{e}&{g}))+{constants[i]}+w{i%16};',
            f' uint32_t t2=(YSKAR_ROTR({a},2)^YSKAR_ROTR({a},13)^YSKAR_ROTR({a},22))+(({a}&{b})^({a}&{c})^({b}&{c})); {d}+=t1; {h}=t1+t2; }}']
 lines += [' '+''.join(f's[{i}]+={name};' for i,name in enumerate('abcdefgh')),'}']
 nonce=source.split('YSKAR_FN void yskar_hash_nonce',1)[1].split('/*\n * hash <=',1)[0]
 nonce='__device__ __forceinline__ void gz_hash_nonce'+nonce
 nonce=nonce.replace('yskar_sha_block','gz_sha_block')
 return '\n'.join(lines)+'\n'+nonce
if __name__=='__main__':
 (ROOT/'fast_sha.cuh').write_text(generate(),encoding='utf-8')
